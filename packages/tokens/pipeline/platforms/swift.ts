import { fmt } from '../format-number.ts';
import { MODES } from '../model.ts';
import {
  colorNames,
  schemeId,
  themeModes,
  type PlatformModel,
} from './model.ts';

export function swiftColor(hex: string): string {
  const h = hex.slice(1);
  const byte = (i: number) => parseInt(h.slice(i, i + 2), 16) / 255;
  const opacity = h.length === 8 ? byte(6) : 1;
  return `Color(.sRGB, red: ${fmt(byte(0))}, green: ${fmt(byte(2))}, blue: ${fmt(byte(4))}, opacity: ${fmt(opacity)})`;
}

const enumCase = (theme: string) => `\`${theme}\``;

export function renderSwift(model: PlatformModel): string {
  const names = colorNames(model);
  const lines = [
    '// Generated by @gremorie/tokens (nx build tokens). Do not edit.',
    '// Gremorie semantic colours per theme and mode, gamut mapped to sRGB.',
    'import SwiftUI',
    '',
    'public struct GremorieColors: Sendable {',
    ...names.map((n) => `    public let ${n}: Color`),
    '}',
    '',
    'public enum GremorieTheme: String, CaseIterable, Sendable {',
    ...model.themeNames.map((t) => `    case ${enumCase(t)}`),
    '}',
    '',
    'extension GremorieTheme {',
    '    public func colors(dark: Bool) -> GremorieColors {',
    '        switch self {',
    ...model.themeNames.map(
      (t) =>
        `        case .${enumCase(t)}: return dark ? GremorieColors.${schemeId(t, 'dark')} : GremorieColors.${schemeId(t, 'light')}`,
    ),
    '        }',
    '    }',
    '}',
    '',
    'extension GremorieColors {',
  ];
  for (const theme of model.themeNames) {
    const modes = themeModes(model, theme);
    for (const mode of MODES) {
      const colors = modes[mode].colors;
      lines.push(
        `    public static let ${schemeId(theme, mode)} = GremorieColors(`,
      );
      names.forEach((n, i) => {
        const color = colors[n];
        if (!color) throw new Error(`${theme}/${mode} has no colour ${n}`);
        const comma = i < names.length - 1 ? ',' : '';
        lines.push(`        ${n}: ${swiftColor(color.hex)}${comma}`);
      });
      lines.push('    )', '');
    }
  }
  lines.push('}', '');
  return lines.join('\n');
}
